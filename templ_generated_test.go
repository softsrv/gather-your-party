package main

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"
)

// CLM-16 (static): every .templ source has its generated _templ.go beside it,
// produced by the templ version go.mod pins (what `make templ` runs). Content
// drift is caught by running `make templ` and diffing.
func TestGeneratedTemplFilesMatchPinnedVersion(t *testing.T) {
	mod, err := os.ReadFile("go.mod")
	if err != nil {
		t.Fatal(err)
	}
	m := regexp.MustCompile(`(?m)^\s*github\.com/a-h/templ\s+(v\S+)`).FindSubmatch(mod)
	if m == nil {
		t.Fatal("go.mod does not pin github.com/a-h/templ")
	}
	want := "// templ: version: " + string(m[1])
	sources, err := filepath.Glob(filepath.Join("internal", "*", "*.templ"))
	if err != nil {
		t.Fatal(err)
	}
	if len(sources) == 0 {
		t.Fatal("found no .templ sources")
	}
	for _, source := range sources {
		generated := strings.TrimSuffix(source, ".templ") + "_templ.go"
		code, err := os.ReadFile(generated)
		if err != nil {
			t.Errorf("%s has no generated %s: %v", source, generated, err)
			continue
		}
		if !strings.Contains(string(code), want) {
			t.Errorf("%s was not generated by the pinned templ (%s)", generated, want)
		}
	}
}
